"""Proxy management for Kaithem.

A :class:`Proxy` exposes a backend HTTP server (or a Unix domain socket)
on its own subdomain, appears on the apps page, requires a configurable
set of permissions, and transparently supports websockets.

Proxies are normally created programmatically::

    from kaithem.api.proxies import Proxy

    proxy = Proxy(
        subdomain="myapp",
        target="http://127.0.0.1:8080",
        permissions=["view_status"],
    )
    ...
    proxy.close()

They can also be created as a ``proxy`` resource from the modules UI.
"""

from __future__ import annotations

import asyncio
import base64
import threading
import time
from collections.abc import Callable
from typing import Any
from urllib.parse import quote, urlparse

import niquests
import quart
import structlog
from websockets.asyncio.client import connect as ws_connect
from websockets.asyncio.client import unix_connect as ws_unix_connect
from websockets.exceptions import ConnectionClosed

import kaithem.api.apps_page as apps_page
from kaithem.api import lifespan, web
from kaithem.src import pages

logger = structlog.get_logger(__name__)

# Headers that only apply to a single hop and must never be forwarded.
_HOP_BY_HOP_HEADERS = frozenset(
    {
        "connection",
        "keep-alive",
        "proxy-authenticate",
        "proxy-authorization",
        "te",
        "trailer",
        "trailers",
        "transfer-encoding",
        "upgrade",
    }
)

# Headers that describe the websocket handshake.  These are regenerated by
# the websocket client, so they must be dropped when forwarding a handshake.
_WEBSOCKET_HANDSHAKE_HEADERS = frozenset(
    {
        "sec-websocket-key",
        "sec-websocket-version",
        "sec-websocket-protocol",
        "sec-websocket-extensions",
        "sec-websocket-accept",
    }
)

_AUTH_COOKIE_NAME = "kaithem_auth"

# Chunk size used when streaming proxied responses.
_STREAM_CHUNK_SIZE = 64 * 1024

# A hook that may inspect or rewrite the headers sent to the backend.
# It receives the ASGI scope, the authenticated username, and the headers
# that would otherwise be forwarded, and may return a replacement dict.
# Returning ``None`` leaves the headers unchanged.
HeaderInterceptor = Callable[
    [dict[str, Any], str, dict[str, str]], "dict[str, str] | None"
]


def _validate_subdomain(subdomain: str) -> str:
    """Validate and normalize a subdomain label, raising on bad input."""
    if not isinstance(subdomain, str) or not subdomain:
        raise ValueError("Subdomain must be a non-empty string")
    subdomain = subdomain.strip()
    if subdomain != subdomain.lower():
        raise ValueError(f"Subdomain {subdomain!r} must be lowercase")
    if "." in subdomain:
        raise ValueError(
            f"Subdomain {subdomain!r} must be a single DNS label, without dots"
        )
    allowed = set("abcdefghijklmnopqrstuvwxyz0123456789-")
    if any(char not in allowed for char in subdomain):
        raise ValueError(
            f"Subdomain {subdomain!r} may only contain letters, digits, "
            "and hyphens"
        )
    if subdomain.startswith("-") or subdomain.endswith("-"):
        raise ValueError(
            f"Subdomain {subdomain!r} may not start or end with a hyphen"
        )
    return subdomain


def _parse_target(target: str) -> tuple[str, str]:
    """Parse a proxy target into a ``(kind, value)`` pair.

    ``kind`` is ``"http"``, ``"https"``, or ``"unix"``.  For HTTP targets
    ``value`` is the ``host[:port]`` authority, and for unix targets it is
    the absolute path of the socket.
    """
    if not isinstance(target, str) or not target:
        raise ValueError("Target must be a non-empty string")

    if target.startswith("unix:"):
        remainder = target[len("unix:") :]
        remainder = remainder.removeprefix("//")
        if not remainder.startswith("/"):
            raise ValueError(
                "Unix socket targets must use an absolute path, "
                "for example 'unix:///run/app.sock'"
            )
        return ("unix", remainder)

    parts = urlparse(target)
    if parts.scheme not in ("http", "https"):
        raise ValueError(
            f"Target {target!r} must start with http://, https://, or unix:"
        )
    if not parts.hostname:
        raise ValueError(f"Target {target!r} is missing a host")
    if parts.path not in ("", "/") or parts.query or parts.fragment:
        raise ValueError(
            f"Target {target!r} must not include a path, query, or fragment"
        )
    return (parts.scheme, parts.netloc)


def _host(scope: dict[str, Any]) -> str:
    for key, value in scope.get("headers", []):
        if key == b"host":
            return value.decode("latin-1")
    return ""


def _parent_host(host: str, subdomain: str) -> str:
    """Return ``host`` with the leading ``subdomain.`` label removed."""
    prefix = subdomain + "."
    if host.startswith(prefix):
        return host[len(prefix) :]
    return host


def _apps_page_url(subdomain: str) -> str:
    """Return the absolute URL for a proxy subdomain.

    Uses the host of the current request when one is active so the link
    points at the same deployment the user is already browsing.
    """
    try:
        host = quart.request.host
    except RuntimeError:
        return f"//{subdomain}/"
    return f"//{subdomain}.{_parent_host(host, subdomain)}/"


def _request_url(scope: dict[str, Any]) -> str:
    """Rebuild the full URL a client requested, as seen by the proxy."""
    scheme = scope.get("scheme", "http")
    path = scope.get("path", "/")
    query = scope.get("query_string", b"").decode("latin-1")
    url = f"{scheme}://{_host(scope)}{path}"
    if query:
        url += "?" + query
    return url


def _strip_auth_cookie(cookie_header: str) -> str:
    """Remove the Kaithem auth cookie from a Cookie header value."""
    kept = []
    for part in cookie_header.split(";"):
        name = part.split("=", 1)[0].strip()
        if name == _AUTH_COOKIE_NAME:
            continue
        kept.append(part)
    return ";".join(kept).strip()


def _get_subprotocols(scope: dict[str, Any]) -> list[str]:
    for key, value in scope.get("headers", []):
        if key == b"sec-websocket-protocol":
            return [
                item.strip()
                for item in value.decode("latin-1").split(",")
                if item.strip()
            ]
    return []


class ProxyApp(apps_page.App):
    """An apps page entry that links straight to a proxy's subdomain."""

    def __init__(
        self,
        subdomain: str,
        title: str,
        module: str | None = None,
        resource: str | None = None,
    ):
        super().__init__(
            id="proxy_" + subdomain,
            title=title,
            url="",
            module=module,
            resource=resource,
        )
        self.subdomain = subdomain

    @property
    def url(self) -> str:
        return _apps_page_url(self.subdomain)

    @url.setter
    def url(self, value: str) -> None:
        # App.__init__ assigns self.url; we always compute it dynamically.
        pass


class Proxy:
    """Expose a backend server on a Kaithem subdomain.

    The proxy registers itself on creation and must be closed with
    :meth:`close` when it is no longer needed.  Dropping a live proxy
    without closing it logs a warning (except during shutdown).
    """

    def __init__(
        self,
        subdomain: str,
        target: str,
        title: str | None = None,
        permissions: list[str] | None = None,
        module: str | None = None,
        resource: str | None = None,
        request_header_interceptors: list[HeaderInterceptor] | None = None,
    ):
        """Create and register a proxy.

        Args:
            subdomain: A single DNS label such as ``"myapp"``.  The proxy
                is reachable at ``<subdomain>.<kaithem host>``.
            target: The backend to forward to.  Either an ``http://`` or
                ``https://`` URL, or ``unix:///path/to.sock``.
            title: Title shown on the apps page.  Defaults to the
                subdomain.
            permissions: Permissions a user must have to reach the
                backend.  An empty list allows any user.
            module: Module name, used for the apps page icon.
            resource: Resource name, used for the apps page icon.
            request_header_interceptors: Hooks that may add to or rewrite
                the headers forwarded to the backend.  They run in order
                after the standard headers are built.
        """
        self.subdomain = _validate_subdomain(subdomain)
        self.target = target
        self.kind, self.target_value = _parse_target(target)
        self.title = title or self.subdomain
        self.permissions = list(permissions or [])
        self.module = module
        self.resource = resource
        self.request_header_interceptors = list(
            request_header_interceptors or []
        )

        self._session: niquests.AsyncSession | None = None
        self._closed = False
        self._app: ProxyApp | None = ProxyApp(
            self.subdomain, self.title, module, resource
        )

        # Register with the subdomain dispatcher first, so a failure to
        # register the app entry does not leave a half built proxy.
        web.add_subdomain_app(self.subdomain, self)
        try:
            apps_page.add_app(self._app)
        except Exception:
            web.remove_subdomain_app(self.subdomain, self)
            self._app = None
            raise

    def __del__(self) -> None:
        try:
            closed = self._closed
            subdomain = self.subdomain
        except Exception:  # pragma: no cover - partially constructed object
            return
        if closed:
            return
        if lifespan.is_shutting_down:
            return
        logger.warning(
            "Proxy for subdomain %r was garbage collected without being "
            "closed; call close() to release it",
            subdomain,
        )

    # -- Public API ---------------------------------------------------

    def add_permission(self, permission: str) -> None:
        """Require an additional permission to reach the backend."""
        if permission not in self.permissions:
            self.permissions.append(permission)

    def close(self) -> None:
        """Unregister the proxy.  Safe to call more than once."""
        if self._closed:
            return
        self._closed = True

        if self._app is not None:
            apps_page.remove_app(self._app)
            self._app = None
        web.remove_subdomain_app(self.subdomain, self)

        session = self._session
        self._session = None
        if session is not None:
            self._close_session(session)

    def apps_page_url(self) -> str:
        """Return the URL the apps page links to for this proxy."""
        return _apps_page_url(self.subdomain)

    # -- Internals ----------------------------------------------------

    def _close_session(self, session: niquests.AsyncSession) -> None:
        loop = getattr(quart.app, "main_web_loop", None)
        if loop is None or not loop.is_running():
            return
        try:
            asyncio.run_coroutine_threadsafe(session.close(), loop)
        except Exception:  # pragma: no cover - loop shutting down
            pass

    def _get_session(self) -> niquests.AsyncSession:
        if self._session is None:
            session = niquests.AsyncSession()
            if self.kind == "unix":
                from niquests.extensions.unixsocket._async import (
                    AsyncUnixAdapter,
                )

                session.mount("http+unix://", AsyncUnixAdapter())
            self._session = session
        return self._session

    def _is_authorized(self, user: str) -> bool:
        if not self.permissions:
            return True
        return pages.canUserDoThis(self.permissions, user)

    def _upstream_host(self) -> str:
        if self.kind == "unix":
            return "localhost"
        return self.target_value

    def _upstream_origin(self) -> str:
        if self.kind == "unix":
            return "http://localhost"
        return f"{self.kind}://{self.target_value}"

    def _upstream_url(self, path: str, query: str) -> str:
        if self.kind == "unix":
            base = "http+unix://" + quote(self.target_value, safe="")
        else:
            base = f"{self.kind}://{self.target_value}"
        url = base + path
        if query:
            url += "?" + query
        return url

    def _build_request_headers(
        self,
        scope: dict[str, Any],
        user: str,
        for_websocket: bool = False,
    ) -> dict[str, str]:
        headers: dict[str, str] = {}
        cookie_parts: list[str] = []
        for key, value in scope.get("headers", []):
            name = key.decode("latin-1")
            lower = name.lower()
            text = value.decode("latin-1")
            if lower in _HOP_BY_HOP_HEADERS:
                continue
            if lower in ("host", "content-length", "origin"):
                continue
            if lower.startswith("x-kaithem-"):
                continue
            if lower == "cookie":
                cleaned = _strip_auth_cookie(text)
                if cleaned:
                    cookie_parts.append(cleaned)
                continue
            if for_websocket and lower in _WEBSOCKET_HANDSHAKE_HEADERS:
                continue
            headers[name] = text

        if cookie_parts:
            headers["Cookie"] = "; ".join(cookie_parts)
        if not for_websocket:
            headers["Host"] = self._upstream_host()
        headers["Origin"] = self._upstream_origin()
        headers["x-kaithem-username"] = user
        headers["x-kaithem-is-admin"] = (
            "true" if pages.canUserDoThis("system_admin", user) else "false"
        )
        for interceptor in self.request_header_interceptors:
            replacement = interceptor(scope, user, headers)
            if replacement is not None:
                headers = replacement
        return headers

    def _build_response_headers(
        self, resp: niquests.AsyncResponse
    ) -> list[tuple[bytes, bytes]]:
        out: list[tuple[bytes, bytes]] = []
        raw_headers = getattr(resp.raw, "headers", None)
        if raw_headers is not None:
            items = raw_headers.items()
        else:  # pragma: no cover - defensive, should not happen
            items = resp.headers.items()
        for key, value in items:
            lower = key.lower()
            if lower in _HOP_BY_HOP_HEADERS:
                continue
            # We always re-chunk the body, so a stale content length must go.
            if lower == "content-length":
                continue
            if lower == "set-cookie" and value.startswith(
                _AUTH_COOKIE_NAME + "="
            ):
                continue
            out.append((key.encode("latin-1"), value.encode("latin-1")))
        return out

    async def _read_body(self, receive) -> bytes:
        chunks: list[bytes] = []
        while True:
            message = await receive()
            if message["type"] == "http.request":
                chunks.append(message.get("body", b""))
                if not message.get("more_body", False):
                    break
            elif message["type"] == "http.disconnect":
                break
        return b"".join(chunks)

    async def _deny_http(self, scope: dict[str, Any], send) -> None:
        url = _request_url(scope)
        check = scope.get("path", "/")
        query = scope.get("query_string", b"").decode("latin-1")
        if query:
            check += "?" + query

        if "login" in check:
            body = b"Forbidden"
            await send(
                {
                    "type": "http.response.start",
                    "status": 403,
                    "headers": [
                        (b"content-type", b"text/plain; charset=utf-8"),
                        (b"content-length", str(len(body)).encode()),
                    ],
                }
            )
            await send({"type": "http.response.body", "body": body})
            return

        parent = _parent_host(_host(scope), self.subdomain)
        target = (
            f"//{parent}/login?go="
            + base64.b64encode(url.encode()).decode()
            + "&maxgotime-"
            + str(time.time() + 300)
        )
        await send(
            {
                "type": "http.response.start",
                "status": 302,
                "headers": [(b"location", target.encode("latin-1"))],
            }
        )
        await send({"type": "http.response.body", "body": b""})

    async def _bad_gateway(self, send) -> None:
        body = b"Bad Gateway"
        await send(
            {
                "type": "http.response.start",
                "status": 502,
                "headers": [
                    (b"content-type", b"text/plain; charset=utf-8"),
                    (b"content-length", str(len(body)).encode()),
                ],
            }
        )
        await send({"type": "http.response.body", "body": body})

    async def _handle_http(self, scope, receive, send) -> None:
        user = pages.getAcessingUser(asgi=scope)
        if not self._is_authorized(user):
            await self._deny_http(scope, send)
            return

        body = await self._read_body(receive)
        method = scope["method"]
        headers = self._build_request_headers(scope, user)

        raw_path = scope.get("raw_path")
        if raw_path:
            path = raw_path.decode("latin-1")
        else:
            path = quote(scope.get("path", "/"))
        query = scope.get("query_string", b"").decode("latin-1")
        url = self._upstream_url(path, query)

        try:
            resp = await self._get_session().request(
                method,
                url,
                headers=headers,
                data=body if body else None,
                allow_redirects=False,
                stream=True,
            )
        except Exception:
            logger.exception("Error proxying request to %s", self.target)
            await self._bad_gateway(send)
            return

        try:
            status = resp.status_code
            out_headers = self._build_response_headers(resp)
            no_body = method == "HEAD" or status in (204, 304)
            await send(
                {
                    "type": "http.response.start",
                    "status": status,
                    "headers": out_headers,
                }
            )
            if no_body:
                await send({"type": "http.response.body", "body": b""})
            else:
                async for chunk in await resp.iter_raw(_STREAM_CHUNK_SIZE):
                    if chunk:
                        await send(
                            {
                                "type": "http.response.body",
                                "body": chunk,
                                "more_body": True,
                            }
                        )
                await send(
                    {
                        "type": "http.response.body",
                        "body": b"",
                        "more_body": False,
                    }
                )
        finally:
            await resp.close()

    def _websocket_uri(self, scope: dict[str, Any]) -> str:
        secure = scope.get("scheme") == "wss" or self.kind == "https"
        scheme = "wss" if secure else "ws"
        host = "localhost" if self.kind == "unix" else self.target_value
        path = scope.get("path", "/")
        query = scope.get("query_string", b"").decode("latin-1")
        uri = f"{scheme}://{host}{path}"
        if query:
            uri += "?" + query
        return uri

    async def _relay_websocket(self, receive, send, backend) -> None:
        async def client_to_backend() -> None:
            while True:
                message = await receive()
                if message["type"] == "websocket.receive":
                    text = message.get("text")
                    if text is not None:
                        await backend.send(text)
                    else:
                        await backend.send(message.get("bytes") or b"")
                elif message["type"] == "websocket.disconnect":
                    return

        async def backend_to_client() -> None:
            try:
                async for message in backend:
                    if isinstance(message, str):
                        await send({"type": "websocket.send", "text": message})
                    else:
                        await send({"type": "websocket.send", "bytes": message})
            except ConnectionClosed:
                return

        tasks = [
            asyncio.ensure_future(client_to_backend()),
            asyncio.ensure_future(backend_to_client()),
        ]
        try:
            await asyncio.wait(tasks, return_when=asyncio.FIRST_COMPLETED)
        finally:
            for task in tasks:
                task.cancel()
            await asyncio.gather(*tasks, return_exceptions=True)

        try:
            await send({"type": "websocket.close", "code": 1000})
        except Exception:  # pragma: no cover - client already gone
            pass

    async def _handle_websocket(self, scope, receive, send) -> None:
        message = await receive()
        if message["type"] != "websocket.connect":
            return

        user = pages.getAcessingUser(asgi=scope)
        if not self._is_authorized(user):
            await send(
                {
                    "type": "websocket.close",
                    "code": 1008,
                    "reason": "Forbidden",
                }
            )
            return

        headers = self._build_request_headers(scope, user, for_websocket=True)
        subprotocols = _get_subprotocols(scope)
        uri = self._websocket_uri(scope)

        connect_kwargs: dict[str, Any] = {"additional_headers": headers}
        if subprotocols:
            connect_kwargs["subprotocols"] = subprotocols

        try:
            if self.kind == "unix":
                backend = await ws_unix_connect(
                    path=self.target_value, uri=uri, **connect_kwargs
                )
            else:
                backend = await ws_connect(uri, **connect_kwargs)
        except Exception:
            logger.exception("Error connecting websocket to %s", self.target)
            await send(
                {
                    "type": "websocket.close",
                    "code": 1011,
                    "reason": "Bad gateway",
                }
            )
            return

        try:
            await send(
                {
                    "type": "websocket.accept",
                    "subprotocol": backend.subprotocol,
                }
            )
            await self._relay_websocket(receive, send, backend)
        finally:
            await backend.close()

    async def __call__(self, scope, receive, send) -> None:
        if scope["type"] == "http":
            await self._handle_http(scope, receive, send)
        elif scope["type"] == "websocket":
            await self._handle_websocket(scope, receive, send)
        else:  # pragma: no cover - dispatcher never sends other types
            raise RuntimeError(
                f"Proxy cannot handle scope type {scope['type']!r}"
            )
